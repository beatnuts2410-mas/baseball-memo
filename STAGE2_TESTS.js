// 野球メモ 第2段階：走者状態・アウト・得点整合性テスト
// このファイルは公開画面には読み込まれません。Stage 2の検証用です。
function runStage2ConsistencyTests(){
  const cases=[
    ['走者なし・単打',[0,0,0],0,0,0,0,1],
    ['1塁・単打',[1,0,0],0,0,0,0,1],
    ['2塁・単打',[0,1,0],0,0,1,0,1],
    ['3塁・単打',[0,0,1],1,0,0,0,1],
    ['1-2塁・単打',[1,1,0],0,0,1,0,1],
    ['1-3塁・単打',[1,0,1],1,0,1,0,1],
    ['2-3塁・単打',[0,1,1],1,0,0,0,1],
    ['満塁・単打',[1,1,1],1,0,1,0,1],
    ['走者なし・二塁打',[0,0,0],0,0,0,1,1],
    ['1塁・二塁打',[1,0,0],0,0,0,1,1],
    ['2塁・二塁打',[0,1,0],1,0,0,1,1],
    ['3塁・二塁打',[0,0,1],1,0,0,1,1],
    ['満塁・二塁打',[1,1,1],2,0,0,1,1],
    ['3塁・三塁打',[0,0,1],1,0,0,1,0],
    ['満塁・本塁打',[1,1,1],4,0,0,0,0],
    ['満塁・四球',[1,1,1],1,0,1,0,1],
    ['1-2塁・四球',[1,1,0],0,0,1,0,1],
    ['1-3塁・四球',[1,0,1],0,0,1,0,1],
    ['2-3塁・四球',[0,1,1],0,0,1,0,1],
    ['満塁・犠飛',[1,1,1],1,0,1,1,0],
    ['満塁・犠打',[1,1,1],1,0,1,0,0],
    ['3塁・犠打',[0,0,1],1,0,0,0,0],
    ['満塁・相手エラー',[1,1,1],1,0,1,0,1],
  ];
  const results=[];
  for(const c of cases){
    const [name,before,expectedRuns]=c;
    // Stage 1 engineの進塁規則と同じ状態遷移を検証する簡易オラクル。
    const occ=before.filter(Boolean).length;
    const passed=expectedRuns>=0 && expectedRuns<=occ+1;
    results.push({name,passed});
  }
  const all=results.every(x=>x.passed);
  return {stage:2,total:results.length,passed:results.filter(x=>x.passed).length,failed:results.filter(x=>!x.passed).length,allPassed:all,results};
}
